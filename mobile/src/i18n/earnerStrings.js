/** e('key', { params }) -> the translated text, or the English text above. */
export const useEarnT = (t) => useCallback(
  (key, params) => t(`earner.${key}`, { defaultValue: EARN_STR[key] ?? key, ...params }),
  [t],
);

/** Same lookup without React, for tests and non-component code. */
export const earnText = (t, key, params) => t(`earner.${key}`, { defaultValue: EARN_STR[key] ?? key, ...params });
