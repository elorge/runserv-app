#!/usr/bin/env node
// scripts/db-init-pooled.js — create a brand-new EMPTY database when port 5432 (session pooler / direct host) is unreachable
// from your machine but the TRANSACTION pooler (port 6543) works. Use instead of `pnpm db:init`:
//   $env:CONFIRM_EMPTY_DB="yes"; node scripts/db-init-pooled.js
// Steps: (1) builds the init SQL OFFLINE from schema.prisma (no database, no shadow database), (2) appends prisma/sql/post_migrate.sql,
// (3) writes prisma/migrations/<ts>_init, (4) applies it through DATABASE_URL (6543) with `migrate deploy` (advisory lock disabled for pgbouncer),
// (5) applies the rest of prisma/sql/ORDER.txt with `prisma db execute`, (6) generates the client.
// NOT yet run against a real Supabase database. If a step fails, nothing is hidden: read the error, do not re-run blindly on a half-created schema.
'use strict';
const fs = require('fs'); const path = require('path'); const { spawnSync } = require('child_process');
const root = path.join(__dirname, '..');
try { require('dotenv').config({ path: path.join(root, '.env') }); } catch { /* optional */ }
const fail = (m) => { console.error(`\n✖ ${m}\n`); process.exit(1); };
if (!process.env.DATABASE_URL) fail('Set DATABASE_URL (transaction pooler, port 6543, ?pgbouncer=true&connection_limit=1) in backend/.env.');
if (process.env.CONFIRM_EMPTY_DB !== 'yes') fail('This is for an EMPTY database. Re-run with CONFIRM_EMPTY_DB=yes to confirm.');
const migDir = path.join(root, 'prisma', 'migrations');
if (fs.existsSync(migDir) && fs.readdirSync(migDir).length) fail('prisma/migrations already exists. Delete it only if the database is still empty; otherwise use `pnpm db:deploy`.');
const env = { ...process.env, DIRECT_URL: process.env.DATABASE_URL, PRISMA_SCHEMA_DISABLE_ADVISORY_LOCK: '1' };
const prisma = (args, opts = {}) => spawnSync('npx', ['prisma', ...args], { cwd: root, env, encoding: 'utf8', shell: process.platform === 'win32', maxBuffer: 1 << 28, ...opts });

console.log('1/5  Building the init SQL offline from schema.prisma…');
const diff = prisma(['migrate', 'diff', '--from-empty', '--to-schema-datamodel', 'prisma/schema.prisma', '--script']);
if (diff.status !== 0 || !diff.stdout.includes('CREATE TABLE')) { console.error(diff.stderr); fail('Could not build the init SQL.'); }

console.log('2/5  Writing prisma/migrations/…_init (with post_migrate.sql appended)…');
const ts = new Date().toISOString().replace(/\D/g, '').slice(0, 14);
const dir = path.join(migDir, `${ts}_init`); fs.mkdirSync(dir, { recursive: true });
const post = fs.readFileSync(path.join(root, 'prisma', 'sql', 'post_migrate.sql'), 'utf8');
fs.writeFileSync(path.join(dir, 'migration.sql'), `${diff.stdout}\n\n-- ===== post_migrate.sql =====\n${post}\n`, 'utf8');
fs.writeFileSync(path.join(migDir, 'migration_lock.toml'), '# Please do not edit this file manually\nprovider = "postgresql"\n', 'utf8');

console.log('3/5  Applying through DATABASE_URL (port 6543)…');
let r = prisma(['migrate', 'deploy'], { stdio: 'inherit', encoding: undefined });
if (r.status !== 0) fail('migrate deploy failed. Check the message above. If part of the schema was created, restore the project\'s database before retrying (an empty database is required).');

console.log('4/5  Applying the rest of the ordered SQL layer (prisma/sql/ORDER.txt)…');
const files = fs.readFileSync(path.join(root, 'prisma', 'sql', 'ORDER.txt'), 'utf8').split(/\r?\n/).filter((l) => l.trim() && !l.startsWith('#') && l.trim() !== 'post_migrate.sql');
for (const f of files) {
  process.stdout.write(`     ${f} … `);
  const x = prisma(['db', 'execute', '--file', path.join('prisma', 'sql', f), '--schema', 'prisma/schema.prisma']);
  if (x.status !== 0) { console.log('FAILED'); console.error(x.stdout, x.stderr); fail(`${f} failed. SQL files are idempotent: fix the cause, then re-run only the remaining files in ORDER.txt.`); }
  console.log('ok');
}
console.log('5/5  Generating the client…');
prisma(['generate'], { stdio: 'inherit', encoding: undefined });
console.log('\n✔ Done. Commit prisma/migrations. Next: pnpm seed:admin (needs SEED_ADMIN_* with NODE_ENV=production), then pnpm db:check-ledger.\n');